/** The share of the icon's width the van takes, and where it sits. */
export interface Layout {
  share: number
  centre: 'icon' | 'viewBox'
}

/**
 * Where the icons centre the van, in the symbol's units: horizontally on its drawn box, vertically
 * 1.25 units above that box's middle (y 54, not 55.25), so the wheels' weight sits in the middle.
 * Every hand-exported icon (and favicon.svg) used this point.
 */
const ICON_CENTRE = { x: 61, y: 54 }

interface Raster {
  path: string
  size: number
  /** White on brand blue (the app icons), or the artwork's own colours. */
  colour: 'white' | 'blue'
  background?: string
  layout: Layout
}

/** `any` icons: the van 72% of the width, on brand blue. */
const ANY: Layout = { share: 0.72, centre: 'icon' }
/** Maskable: 62%, so Android's circle mask never clips it. */
const MASKABLE: Layout = { share: 0.62, centre: 'icon' }
/**
 * Android's adaptive icon: the launcher shows the middle 72/108 of the canvas, so 41% of the width
 * (41.2%, as first exported) is 72% of the launcher circle's radius (at 55% the van nearly touched
 * the circle).
 */
const ADAPTIVE: Layout = { share: 0.412, centre: 'icon' }
/** The splash: 80% of the width, centred on the symbol's own canvas (its viewBox), not `ICON_CENTRE`. */
const SPLASH: Layout = { share: 0.8, centre: 'viewBox' }
/** favicon.svg and favicon.ico: the van edge to edge, on nothing. */
const FAVICON: Layout = { share: 1, centre: 'icon' }

