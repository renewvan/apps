/** The hex each app manifest takes. */
export function manifestColours() {
  return {
    pwaTheme: brand.navy,
    pwaBackground: brand.navy,
    adaptiveIconBackground: brand.blue,
    // The UI accent (≈ #0485f7), as the app's controls draw it, not the artwork's brand blue.
    notification: oklchToHex(light.accent),
    splashLight: oklchToHex(light.background),
    splashDark: oklchToHex(dark.background),
  }
}

function camel(name: string): string {
  return name.replace(/-(\w)/g, (_, letter: string) => letter.toUpperCase())
}

interface Masters {
  white: SvgElement
  blue: SvgElement
  lockup: SvgElement
  /** The van's drawn box in the symbol's units, strokes included. */
  box: { x: number; y: number; width: number; height: number }
  viewBox: { x: number; y: number; width: number; height: number }
}

function readMasters(brandRoot: string): Masters {
  const read = (name: string) => readFileSync(join(brandRoot, 'svg', name), 'utf8')
  const blueXml = read('renewvan-symbol-blue.svg')
  const white = parseSvg(read('renewvan-symbol-white.svg'))
  const blue = parseSvg(blueXml)
  const lockup = parseSvg(read('renewvan-lockup-light.svg'))

  // The masters draw the brand blue themselves: it must be the one in tokens.ts.
  const colours = (element: SvgElement) =>
    new Set(
      innerMarkup(element)
        .toLowerCase()
        .match(/#[0-9a-f]{3,6}\b/g),
    )
  const expect = (name: string, actual: Set<string>, allowed: string[]) => {
    const stray = [...actual].filter((colour) => !allowed.includes(colour))
    if (stray.length) {
      throw new Error(
        `svg/${name} draws ${stray.join(', ')}; tokens.ts brand.blue is ${brand.blue}`,
      )
    }
  }
  expect('renewvan-symbol-blue.svg', colours(blue), [brand.blue, '#fff'])
  expect('renewvan-symbol-white.svg', colours(white), ['#fff'])

  const [x, y, width, height] = blue.attributes.viewBox.split(/\s+/).map(Number)
  const bbox = new Resvg(blueXml).getBBox()
  if (!bbox) throw new Error('svg/renewvan-symbol-blue.svg draws nothing')
  return {
    white,
    blue,
    lockup,
    box: { x: bbox.x, y: bbox.y, width: bbox.width, height: bbox.height },
    viewBox: { x, y, width, height },
  }
}

function composition(
  masters: Masters,
  colour: Raster['colour'],
  size: number,
  layout: Layout,
  background?: string,
) {
  const { viewBox } = masters
  const centre =
    layout.centre === 'icon'
      ? ICON_CENTRE
      : { x: viewBox.x + viewBox.width / 2, y: viewBox.y + viewBox.height / 2 }
  return placeSymbol({
    symbol: innerMarkup(colour === 'white' ? masters.white : masters.blue),
    vanWidth: masters.box.width,
    size,
    share: layout.share,
    centre,
    background,
  })
}

function render(svg: string): Buffer {
  return new Resvg(svg, { fitTo: { mode: 'original' }, font: { loadSystemFonts: false } })
    .render()
    .asPng()
}

/** Format generated source with the workspace's Oxfmt settings (root vite.config.ts). */
function format(repoRoot: string, path: string, source: string): string {
  return execFileSync('vp', ['fmt', `--stdin-filepath=${path}`], {
    cwd: repoRoot,
    input: source,
    encoding: 'utf8',
  })
}

function declarations(theme: Theme, indent: string, extra: string[] = []): string {
  const lines = Object.entries(theme).map(([name, value]) => `${indent}--${name}: ${value};`)
  return [...lines, ...extra.map((line) => `${indent}${line}`)].join('\n')
}

function webCss(): string {
  const radius = [`--radius: ${radiusRem}rem;`, `--field-radius: ${fieldRadiusRem}rem;`]
  return `/* ${HEADER} */

/* HeroUI's theme variables for the dashboard (src/index.css imports this after HeroUI's theme). */
:root,
.light,
.default,
[data-theme='light'],
[data-theme='default'] {
${declarations(light, '  ', radius)}
}

.dark,
[data-theme='dark'] {
${declarations(dark, '  ')}
}
`
}

function nativeCss(): string {
  return `/* ${HEADER} */

/* HeroUI Native's theme variables for Uniwind (mobile src/global.css imports this). */
@theme {
  --radius: ${radiusRem}rem;
  --field-radius: ${fieldRadiusRem}rem;
}

@layer theme {
  :root {
    @variant light {
${declarations(light, '      ')}
    }

    @variant dark {
${declarations(dark, '      ')}
    }
  }
}
`
}

function paletteTs(): string {
  const fields = PALETTE.map((name) => `  ${camel(name)}: string`).join('\n')
  const values = (theme: Theme) =>
    PALETTE.map((name) => {
      const value = theme[name]
      if (!value) throw new Error(`tokens.ts has no ${name}`)
      return `    ${camel(name)}: '${oklchToHex(value)}',`
    }).join('\n')
  return `// ${HEADER}
//
// The theme tokens as sRGB hex, for React Native (no CSS custom properties, no oklch): mobile's
// hand-drawn parts read these. Same names as the CSS variables, camel-cased.

export interface Palette {
${fields}
}

export const palettes: { light: Palette; dark: Palette } = {
  light: {
${values(light)}
  },
  dark: {
${values(dark)}
  },
}
`
}

type LogoValue = string | number

interface LogoElement {
  name: string
  props: Record<string, LogoValue>
  children: LogoElement[]
}

function logoElement(element: SvgElement): LogoElement {
  const props: Record<string, LogoValue> = {}
  for (const [key, value] of Object.entries(element.attributes)) {
    if (key === 'xmlns' || key.includes(':')) continue
    props[camel(key)] =
      value.toLowerCase() === brand.blue
        ? 'currentColor'
        : /^-?\d+(\.\d+)?$/.test(value)
          ? Number(value)
          : value
  }
  const children = element.children.map((child) => {
    if (typeof child === 'string') throw new Error(`Text in the symbol: ${child}`)
    return logoElement(child)
  })
  return { name: element.name, props, children }
}

function logoTs(masters: Masters): string {
  const symbol = masters.blue.children.map((child) => {
    if (typeof child === 'string') throw new Error(`Text in the symbol: ${child}`)
    return logoElement(child)
  })
  const names = new Set<string>()
  const collect = (element: LogoElement) => {
    names.add(element.name)
    element.children.forEach(collect)
  }
  symbol.forEach(collect)

  const text = findElement(masters.lockup, 'text')
  const wordmark = text.children.map((part) =>
    typeof part === 'string'
      ? { text: part, brand: false }
      : { text: textOf(part), brand: part.attributes.fill?.toLowerCase() === brand.blue },
  )
  const { viewBox } = masters
  return `// ${HEADER}
//
// The logo for react-native-svg (mobile src/components/Logo.tsx), read from the masters: the symbol
// (svg/renewvan-symbol-blue.svg) as elements, its brand blue as \`currentColor\`, and the lockup's
// wordmark (svg/renewvan-lockup-light.svg), \`brand\` where it is drawn in brand blue.

export interface LogoElement {
  name: ${[...names]
    .sort()
    .map((name) => `'${name}'`)
    .join(' | ')}
  props: Record<string, string | number>
  children: LogoElement[]
}

export const logoSymbol: {
  viewBox: string
  width: number
  height: number
  children: LogoElement[]
} = {
  viewBox: '${masters.blue.attributes.viewBox}',
  width: ${viewBox.width},
  height: ${viewBox.height},
  children: ${JSON.stringify(symbol)},
}

export const logoWordmark: { text: string; brand: boolean }[] = ${JSON.stringify(wordmark)}
`
}

function findElement(element: SvgElement, name: string): SvgElement {
  for (const child of element.children) {
    if (typeof child === 'string') continue
    if (child.name === name) return child
    try {
      return findElement(child, name)
    } catch {
      // not under this child
    }
  }
  throw new Error(`No <${name}>`)
}

/** Replace the one match of `pattern`'s second group (the value) in `text`. */
function replaceOnce(text: string, pattern: RegExp, value: string, what: string): string {
  const matches = text.match(new RegExp(pattern.source, `${pattern.flags.replace('g', '')}g`))
  if (matches?.length !== 1) throw new Error(`Expected one ${what}, found ${matches?.length ?? 0}`)
  return text.replace(
    pattern,
    (_, before: string, _old: string, after: string) => `${before}${value}${after}`,
  )
}

const HEX = '(#[0-9a-fA-F]{6})'

function manifestJson(current: string): string {
  const colours = manifestColours()
  let text = replaceOnce(
    current,
    new RegExp(`("background_color":\\s*")${HEX}(")`),
    colours.pwaBackground,
    'background_color',
  )
  text = replaceOnce(
    text,
    new RegExp(`("theme_color":\\s*")${HEX}(")`),
    colours.pwaTheme,
    'theme_color',
  )
  const parsed = JSON.parse(text)
  if (
    parsed.theme_color !== colours.pwaTheme ||
    parsed.background_color !== colours.pwaBackground
  ) {
    throw new Error('manifest.webmanifest: colours not where expected')
  }
  return text
}

function indexHtml(current: string): string {
  return replaceOnce(
    current,
    new RegExp(`(<meta name="theme-color" content=")${HEX}(")`),
    manifestColours().pwaTheme,
    '<meta name="theme-color">',
  )
}

function appJson(current: string): string {
  const colours = manifestColours()
  let text = replaceOnce(
    current,
    new RegExp(`("adaptiveIcon":\\s*\\{\\s*"backgroundColor":\\s*")${HEX}(")`),
    colours.adaptiveIconBackground,
    'adaptiveIcon.backgroundColor',
  )
  text = replaceOnce(
    text,
    new RegExp(`("expo-notifications",\\s*\\{[^}]*"color":\\s*")${HEX}(")`),
    colours.notification,
    'expo-notifications color',
  )
  text = replaceOnce(
    text,
    new RegExp(`("expo-splash-screen",\\s*\\{[^}]*?"backgroundColor":\\s*")${HEX}(")`),
    colours.splashLight,
    'expo-splash-screen backgroundColor',
  )
  text = replaceOnce(
    text,
    new RegExp(`("dark":\\s*\\{\\s*"backgroundColor":\\s*")${HEX}(")`),
    colours.splashDark,
    'expo-splash-screen dark.backgroundColor',
  )

  // Read it back: every colour where Expo looks for it.
  const { expo } = JSON.parse(text)
  const plugin = (name: string) =>
    expo.plugins.find((entry: unknown) => Array.isArray(entry) && entry[0] === name)?.[1]
  const found = [
    expo.android.adaptiveIcon.backgroundColor,
    plugin('expo-notifications')?.color,
    plugin('expo-splash-screen')?.backgroundColor,
    plugin('expo-splash-screen')?.dark?.backgroundColor,
  ]
  const wanted = [
    colours.adaptiveIconBackground,
    colours.notification,
    colours.splashLight,
    colours.splashDark,
  ]
  if (found.join() !== wanted.join())
    throw new Error(`app.json: colours not where expected (${found.join(', ')})`)
  return text
}

export function buildOutputs(repoRoot: string): Output[] {
  const brandRoot = join(repoRoot, 'packages/brand')
  const masters = readMasters(brandRoot)
  const current = (path: string) => readFileSync(join(repoRoot, path), 'utf8')
  const text = (path: string, source: string): Output => ({
    path,
    kind: 'text',
    data: Buffer.from(source),
  })
  const formatted = (path: string, source: string) => text(path, format(repoRoot, path, source))

  const favicon = composition(masters, 'blue', 1024, FAVICON)
  const faviconPngs = FAVICON_ICO_SIZES.map((size) =>
    new Resvg(favicon, { fitTo: { mode: 'width', value: size } }).render().asPng(),
  )

  return [
    formatted('packages/brand/tokens.web.css', webCss()),
    formatted('packages/brand/tokens.native.css', nativeCss()),
    formatted('packages/brand/src/palette.ts', paletteTs()),
    formatted('packages/brand/src/logo.ts', logoTs(masters)),
    text('dashboard/public/favicon.svg', `${favicon}\n`),
    { path: 'dashboard/public/favicon.ico', kind: 'ico', data: encodeIco(faviconPngs) },
    ...RASTERS.map((raster): Output => ({
      path: raster.path,
      kind: 'png',
      data: render(
        composition(masters, raster.colour, raster.size, raster.layout, raster.background),
      ),
    })),
    text(
      'dashboard/public/manifest.webmanifest',
      manifestJson(current('dashboard/public/manifest.webmanifest')),
    ),
    text('dashboard/index.html', indexHtml(current('dashboard/index.html'))),
    text('mobile/app.json', appJson(current('mobile/app.json'))),
  ]
}
